#!/usr/bin/env python3
"""Generate N translation units for the Bazel remote-execution benchmark.

Each generated .cpp instantiates a compile-time Fibonacci suite (see
include/bench/fib.hpp) with a unique Id, forcing the compiler to do real,
non-cacheable work. Mirrors the CMake BENCHMARK_TU_COUNT project, but for Bazel.

Usage:
    python3 tools/generate_tus.py --count 20000 --depth 22 --stamp default
"""

import argparse
import os
import shutil

TU_TEMPLATE = """\
#include "bench/fib.hpp"

// RE Benchmark TU {id} of {count} (depth={depth}, stamp="{stamp}")
namespace bench_tu_{id} {{
constexpr unsigned long long result = ::bench::slow_fib<{depth}, {id}>();
unsigned long long sink() {{ return result; }}
}}  // namespace bench_tu_{id}
"""

BUILD_HEADER = """\
# AUTO-GENERATED by tools/generate_tus.py -- do not edit by hand.
# Regenerate with: python3 tools/generate_tus.py --count N --depth D --stamp S

load("@rules_cc//cc:defs.bzl", "cc_library")

package(default_visibility = ["//visibility:public"])

"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=20000,
                    help="number of translation units to generate")
    ap.add_argument("--depth", type=int, default=22,
                    help="Fibonacci template depth (compile cost grows ~2^depth)")
    ap.add_argument("--stamp", default="default",
                    help="cache-busting stamp; change to force recompilation")
    ap.add_argument("--out", default=None,
                    help="output dir for the generated TUs (default: generated/)")
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)  # bazel/
    out = args.out or os.path.join(root, "generated")

    srcs_dir = os.path.join(out, "srcs")
    if os.path.isdir(srcs_dir):
        shutil.rmtree(srcs_dir)
    os.makedirs(srcs_dir)

    names = []
    for i in range(1, args.count + 1):
        fname = "benchmark_unit_%d.cpp" % i
        with open(os.path.join(srcs_dir, fname), "w") as f:
            f.write(TU_TEMPLATE.format(
                id=i, count=args.count, depth=args.depth, stamp=args.stamp))
        names.append(fname)

    with open(os.path.join(out, "BUILD.bazel"), "w") as f:
        f.write(BUILD_HEADER)
        f.write('cc_library(\n')
        f.write('    name = "re_benchmark_lib",\n')
        f.write('    srcs = glob(["srcs/*.cpp"]),\n')
        f.write('    deps = ["//include:bench"],\n')
        f.write('    copts = ["-std=c++17"],\n')
        f.write(')\n')

    print("Generated %d TUs (depth=%d, stamp=%r) in %s"
          % (args.count, args.depth, args.stamp, srcs_dir))


if __name__ == "__main__":
    main()
